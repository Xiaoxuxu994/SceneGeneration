def dit_latent_occ_to_udf_to_mcmesh(cond_path, occ_path, udf_mcmesh_path, udf_slice_path, grid_size=0.05, alpha=2):
    """ 
        function: transfer occ filed to udf field, then use Marching Cube(MC) to reconstruct mesh 
                    occ field is decoded from latent generated by dit with bbox condition
                    bbox condition is used to constrain the udf field grid
        cond_path: file path of conditon in dit generation, size = [B,1,6]: [6]= [cx,cy,cz,lx,ly,lz]
        occ_path: file path of occ field decoded from dit generated latent with condition, size = dict{B}
        udf_mcmesh_path: path to save transfered udf field and MC mesh, should exist before func call
        udf_slice_path: path to save transfered udf field slice, should exist before fun call
        grid_size: udf grid size
        alpha: marching cube arguments, do not change
    """ 
    bbox_array = torch.load(cond_path, map_location='cpu')
    occ_dict = torch.load(occ_path, map_location='cpu')
    ## get udf of each scene
    for idx in tqdm(range(bbox_array.shape[0]), total=bbox_array.shape[0], desc="Decoding latents"):
        bbox = bbox_array[idx].squeeze(0).numpy()
        # load latent decode query 0.05 pointcloud in each pth file
        query_pcd = occ_dict[str(idx)].numpy()
        tqdm.write(f'{idx} sample =  {bbox} occ number = {query_pcd.shape[0]}')
        # get grid size of udf field (keep same with id=1)
        center = np.array(bbox[0:3])
        edge = np.array(bbox[3:6])
        min_bound = center - edge/2
        dims = np.ceil( edge / grid_size).astype(int)
        # initialzie udf field
        udf_grid = np.full(dims, np.inf)
        # make kdtree
        kdtree = KDTree(query_pcd)
        # traverse each point of udf field to find nearest point in pointcloud
        for i in range(dims[0]):
            for j in range(dims[1]):
                for k in range(dims[2]):
                    grid_point = min_bound + np.array([i, j, k]) * grid_size
                    dist, _ = kdtree.query(grid_point)
                    udf_grid[i, j, k] = dist
        # save slice of udf field
        slice = udf_grid[:,:, dims[2] // 2]
        slice_norm = ((slice - slice.min()) / (slice.max() - slice.min()) * 255).astype(np.uint8)
        slice_colored = cv2.applyColorMap(slice_norm, cv2.COLORMAP_JET)
        slice_colored = cv2.resize(slice_colored, (dims[1]*6, dims[0]*6), interpolation=cv2.INTER_CUBIC)
        cv2.imwrite(os.path.join(udf_slice_path, str(idx) + '.png'), slice_colored)
        # get surface by marching cube 
        vertices, faces, _, _ = measure.marching_cubes(udf_grid, level=grid_size*alpha, spacing=(grid_size, grid_size, grid_size))
        # save surface vertices and faces
        np.savez(os.path.join(udf_mcmesh_path, str(idx) + '.npz'), udf=udf_grid, vert=vertices, face=faces)

def mesh_pcd_to_udf_to_mcmesh(pcd_path_list, udf_mcmesh_path, udf_slice_path, grid_size=0.05, alpha=2):
    """ 
        function: transfer original mesh pointcloud to udf field, then use marching cube to reconstruct mesh 
        pcd_path_list: a list of point cloud file paths, may be multiple folders
        udf_mcmesh_path: path to save transfered udf field and MC mesh, should exist before func call
        udf_slice_path: path to save transfered udf field slice, should exist before fun call
        grid_size: udf grid size
        alpha: marching cube arguments, do not change
    """ 
    ## list all file in pcd_path_list
    file_list = []
    file_sha256 = []
    for path in pcd_path_list:
        for _, file in enumerate(os.listdir(path)):
            file_list.append(os.path.join(path, file))
            file_sha256.append(file.rsplit('.')[0])
    ## get udf of each scene
    for i, item in tqdm(enumerate(zip(file_list,file_sha256)), total=len(file_list), desc="Processing"):
        file, sha256 = item
        tqdm.write(f"i = {i}, sha256 = {sha256} file={file}")
        # load mesh pointcloud in each pth file
        tmp = torch.load(file, weights_only=False, map_location='cpu')
        mesh_pcd = tmp["coord"]
        # get bound of mesh pointcloud
        min_bound = np.min(mesh_pcd, axis=0)
        max_bound = np.max(mesh_pcd, axis=0)
        # get grid size of udf field
        dims = np.ceil((max_bound - min_bound) / grid_size).astype(int)
        # initialzie udf field
        udf_grid = np.full(dims, np.inf)
        # make kdtree
        kdtree = KDTree(mesh_pcd)
        # traverse each point of udf field to find nearest point in pointcloud
        for i in range(dims[0]):
            for j in range(dims[1]):
                for k in range(dims[2]):
                    grid_point = min_bound + np.array([i, j, k]) * grid_size
                    dist, _ = kdtree.query(grid_point)
                    udf_grid[i, j, k] = dist
        # save slice of udf field
        slice = udf_grid[:,:, dims[2] // 2]
        slice_norm = ((slice - slice.min()) / (slice.max() - slice.min()) * 255).astype(np.uint8)
        slice_colored = cv2.applyColorMap(slice_norm, cv2.COLORMAP_JET)
        slice_colored = cv2.resize(slice_colored, (dims[1]*6, dims[0]*6), interpolation=cv2.INTER_CUBIC)
        cv2.imwrite(os.path.join(udf_slice_path, sha256 + '.png'), slice_colored)
        # get surface by marching cube 
        vertices, faces, _, _ = measure.marching_cubes(udf_grid, level=grid_size*alpha, spacing=(grid_size, grid_size, grid_size))
        # save surface vertices and faces
        np.savez(os.path.join(udf_mcmesh_path, sha256 + '.npz'), udf=udf_grid, vert=vertices, face=faces)
        
def recreate_mcmesh(udf_mcmesh_path):
    """
        re-create marching cube surface of a udf_mcmesh_path
    """
    file_list = os.listdir(udf_mcmesh_path)
    grid_size = 0.05
    alpha = 0.55
    for _, file in tqdm(enumerate(file_list), total=len(file_list), desc="Processing"):
        tmp = np.load(file)
        udf_grid = tmp['udf']
        vertices, faces, _, _ = measure.marching_cubes(udf_grid, level=alpha*grid_size, spacing=(grid_size, grid_size, grid_size))
        np.savez(os.path.join(udf_mcmesh_path, file), udf=udf_grid, vert=vertices, face=faces)

