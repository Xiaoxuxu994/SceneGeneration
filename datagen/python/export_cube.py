import os
import argparse

import numpy as np
import open3d as o3d
import multiprocessing as mp

from pathlib import Path

gen_cmd = (
    lambda mode, in_filepath, out_filepath, boxmin, boxmax, grid_size: f"./tools/{mode}_boxgen {in_filepath} {out_filepath} {boxmin} {boxmax} {grid_size}"
)

parser = argparse.ArgumentParser()
parser.add_argument("--in_dir", type=str, required=True)
parser.add_argument("--out_dir", type=str, required=True)
parser.add_argument("--norm_dir", type=str, required=True)
parser.add_argument("--voxel_res", type=int, default=128)
parser.add_argument("--mode", type=str, choices=["sdf", "occ", "udf"])
parser.add_argument("--dataset", type=str, choices=["scannetpp", "arkitscenes", "custom"])
parser.add_argument("--boxmin", type=float, default=-1)
parser.add_argument("--boxmax", type=float, default=1)
parser.add_argument("--boxscale", type=float, default=0.95)
parser.add_argument("--num_workers", type=int, default=1)
parser.add_argument("--simplify", type=float, default=1.0, help="generate volume even if target exists.")
parser.add_argument("--is_norm", action="store_true", help="all input mesh data are normalized.")
parser.add_argument("--force_norm", action="store_true", help="generate cached normalized data even if targets exist.")
parser.add_argument("--force", action="store_true", help="generate volume even if target exists.")
args = parser.parse_args()

in_dir = Path(args.in_dir)
out_dir = Path(args.out_dir)
norm_dir = Path(args.norm_dir)

out_dir.mkdir(exist_ok=True, parents=True)
norm_dir.mkdir(exist_ok=True, parents=True)

voxel_size = (args.boxmax - args.boxmin) / args.voxel_res

def simplify_mesh(mesh, target_ratio=0.2):
    orig_tri_count = len(mesh.triangles)
    target_tri_count = int(orig_tri_count * target_ratio)
    simplified = mesh.simplify_quadric_decimation(target_number_of_triangles=target_tri_count)
    simplified.compute_vertex_normals()
    
    return simplified

def export_norm_mesh(input_path, output_dir):
    print("normalizing mesh file {}".format(str(input_path)))
    mesh = o3d.io.read_triangle_mesh(str(input_path))
    
    if args.simplify < 1.0:
        mesh = simplify_mesh(mesh, args.simplify)
    
    # normalize vertices
    verts = np.array(mesh.vertices)
    shifts = (verts.max(axis=0) + verts.min(axis=0)) / 2
    verts -= shifts
    scale = (args.boxmax - args.boxmin) / (verts.max(axis=0) - verts.min(axis=0)).max()
    scale *= args.boxscale
    verts *= scale
    mesh.vertices = o3d.utility.Vector3dVector(verts)
    
    obj_path = output_dir / "normalized.obj"
    print("writing mesh file to {}".format(str(obj_path)))
    o3d.io.write_triangle_mesh(str(obj_path), mesh)
    
    ply_path = output_dir / "normalized.ply"
    print("writing mesh file to {}".format(str(obj_path)))
    o3d.io.write_triangle_mesh(str(ply_path), mesh)

def worker_job(path):
    if args.dataset == "scannetpp":
        if args.is_norm:
            src_name = path.parent.name
        else:
            src_name = path.parent.parent.name
    elif args.dataset == "arkitscenes":
        src_name = path.parent.name
    elif args.dataset == "custom":
        src_name = path.parent.name
        
    norm_obj_dir = norm_dir / src_name
    norm_obj_dir.mkdir(exist_ok=True, parents=True)
    norm_obj = norm_obj_dir / "normalized.obj"
    if path.exists() and not norm_obj.exists() or args.force_norm:
        export_norm_mesh(path, norm_obj_dir)
    else:
        print("mesh {} already normalized".format(str(path)))
    
    tar_dir = out_dir / args.mode / src_name
    tar_dir.mkdir(exist_ok=True, parents=True)
    tar_path = tar_dir / f"vs_{args.voxel_res}"
    if norm_obj.exists() and not tar_path.with_suffix(".npy").exists() or args.force:
        print("exporting volume file to {}".format(str(tar_path.with_suffix(".npy"))))
        os.system(gen_cmd(args.mode, str(norm_obj), str(tar_path), args.boxmin, args.boxmax, voxel_size))

        # NOTE SDF grids generated by sdf_gen swaps the x and z axes
        # they must be swapped back
        tar_path = tar_dir / f"vs_{args.voxel_res}.npy"
        grid = np.load(tar_path)
        grid = np.transpose(grid, (2, 1, 0))
        np.save(tar_path, grid)
    else:
        print("cube file {} exists".format(str(tar_path.with_suffix(".npy"))))

def main():
    if args.dataset == "scannetpp":
        if args.is_norm:
            src_ply_list = list(map(lambda x: x / "normalized.ply", sorted(list(norm_dir.iterdir()))))
        else:
            src_ply_list = list(map(lambda x: x / "scans/mesh_aligned_0.05.ply", sorted(list(in_dir.iterdir()))))
    elif args.dataset == "arkitscenes":
        if args.is_norm:
            src_ply_list = list(map(lambda x: x / "normalized.ply", sorted(list(norm_dir.iterdir()))))
        else:
            src_ply_list = list(map(lambda x: x / "{}_3dod_mesh.ply".format(str(x.name)), sorted(list(in_dir.iterdir()))))
    elif args.dataset == "custom":
        src_ply_list = list(map(lambda x: x / "mesh.ply", sorted(list(in_dir.iterdir()))))
    
    assert len(src_ply_list) > 0, "empty input data list"
    
    if args.num_workers > 1:
        pool = mp.Pool(processes=args.num_workers)
        pool.map(worker_job, src_ply_list)
    else:
        for src_ply in src_ply_list:
            # for debugging
            worker_job(src_ply)
            exit()

main()