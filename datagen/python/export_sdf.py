import os
import sys
import argparse

import numpy as np
import open3d as o3d
import multiprocessing as mp

from pathlib import Path

sdf_gen_cmd = (
    lambda in_filepath, out_filepath, grid_size, padding: f"./tools/sdf_gen {in_filepath} {out_filepath} {grid_size} {padding}"
)

parser = argparse.ArgumentParser()
parser.add_argument("--in_dir", type=str, required=True)
parser.add_argument("--out_dir", type=str, required=True)
parser.add_argument("--voxel_size", type=float, default=0.05)
parser.add_argument("--padding", type=float, default=1)
parser.add_argument("--num_workers", type=int, default=1)
parser.add_argument("--force_obj", action="store_true", help="generate obj even if target exists.")
parser.add_argument("--force_sdf", action="store_true", help="generate sdf even if target exists.")
args = parser.parse_args()

in_dir = Path(args.in_dir)
out_dir = Path(args.out_dir) / "sdf"

out_dir.mkdir(exist_ok=True, parents=True)

def ply_to_obj(ply_path, obj_path):
    # print(ply_path)
    # print(obj_path)
    mesh = o3d.io.read_triangle_mesh(str(ply_path))
    o3d.io.write_triangle_mesh(str(obj_path), mesh)

def worker_job(path):
    src_name = path.parent.parent.name
    src_obj = path.parent / "mesh_aligned_0.05.obj"
    if not src_obj.exists() or args.force_obj:
        ply_to_obj(path, src_obj)
    
    tar_dir = out_dir / src_name
    tar_dir.mkdir(exist_ok=True, parents=True)
    tar_path = tar_dir / f"vs_{args.voxel_size}m"
    if not tar_path.exists() or args.force_sdf:
        os.system(sdf_gen_cmd(str(src_obj), str(tar_path), args.voxel_size, args.padding))

        # NOTE SDF grids generated by sdf_gen swaps the x and z axes
        # they must be swapped back
        tar_path = tar_dir / f"vs_{args.voxel_size}m.npy"
        grid = np.load(tar_path)
        grid = np.transpose(grid, (2, 1, 0))
        np.save(tar_path, grid)

def main():    
    src_ply_list = list(map(lambda x: x / "scans/mesh_aligned_0.05.ply", sorted(list(in_dir.iterdir()))))
    assert len(src_ply_list) > 0, "empty input data list"
    
    if args.num_workers > 1:
        pool = mp.Pool(processes=args.num_workers)
        pool.map(worker_job, src_ply_list)
    else:
        for src_ply in src_ply_list:
            worker_job(src_ply)

main()